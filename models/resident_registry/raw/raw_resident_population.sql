-- 住民基本台帳に基づく人口・世帯数・人口動態 (resident_registry パイプライン生成の NDJSON)。
-- 団体コードは先頭ゼロを保つため VARCHAR で読む。
SELECT
    reference_date,
    year,
    resident_kind,
    area_level,
    lg_code,
    pref_name,
    municipality_name,
    population_male,
    population_female,
    population_total,
    households,
    moved_in_domestic,
    moved_in_overseas,
    moved_in_total,
    births,
    other_added,
    total_added,
    moved_out_domestic,
    moved_out_overseas,
    moved_out_total,
    deaths,
    other_removed,
    total_removed,
    net_change,
    natural_change,
    social_change
FROM read_json(
    'data/resident_registry/population.ndjson',
    columns = {
        reference_date: 'DATE',
        year: 'INTEGER',
        resident_kind: 'VARCHAR',
        area_level: 'VARCHAR',
        lg_code: 'VARCHAR',
        pref_name: 'VARCHAR',
        municipality_name: 'VARCHAR',
        population_male: 'BIGINT',
        population_female: 'BIGINT',
        population_total: 'BIGINT',
        households: 'BIGINT',
        moved_in_domestic: 'BIGINT',
        moved_in_overseas: 'BIGINT',
        moved_in_total: 'BIGINT',
        births: 'BIGINT',
        other_added: 'BIGINT',
        total_added: 'BIGINT',
        moved_out_domestic: 'BIGINT',
        moved_out_overseas: 'BIGINT',
        moved_out_total: 'BIGINT',
        deaths: 'BIGINT',
        other_removed: 'BIGINT',
        total_removed: 'BIGINT',
        net_change: 'BIGINT',
        natural_change: 'BIGINT',
        social_change: 'BIGINT'
    },
    format = 'newline_delimited'
)
